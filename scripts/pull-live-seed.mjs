// Pulls the publicly readable content from the live Supabase project (read-only, anon key)
// and writes supabase/seed.sql, so `supabase db reset` gives a local copy of the site's content.
// Usage: node scripts/pull-live-seed.mjs   (reads URL + anon key from .env.local)
// Images/PDFs keep pointing at live storage URLs, which are public, so they still display locally.
import { readFileSync, writeFileSync } from "node:fs";

const env = Object.fromEntries(
    readFileSync(".env.local", "utf8")
        .split(/\r?\n/)
        .filter((l) => l.includes("=") && !l.startsWith("#"))
        .map((l) => [l.slice(0, l.indexOf("=")).trim(), l.slice(l.indexOf("=") + 1).trim()])
);
const url = env.LIVE_SUPABASE_URL || env.NEXT_PUBLIC_SUPABASE_URL;
const key = env.LIVE_SUPABASE_ANON_KEY || env.NEXT_PUBLIC_SUPABASE_ANON_KEY;
if (!url || url.includes("127.0.0.1") || url.includes("localhost")) {
    console.error("Set LIVE_SUPABASE_URL / LIVE_SUPABASE_ANON_KEY in .env.local to the live project.");
    process.exit(1);
}

// Parent tables before children (foreign keys).
const TABLES = [
    "site_settings",
    "hero_section",
    "business_hours",
    "gallery_images",
    "categories",
    "menu_items",
    "allergens",
    "menu_item_allergens",
    "wine_categories",
    "wine_items",
    "menus",
];

const lines = [
    "-- Generated by scripts/pull-live-seed.mjs — local development only. Do not run against live.",
    `TRUNCATE ${TABLES.join(", ")} CASCADE;`,
];

for (const table of TABLES) {
    const res = await fetch(`${url}/rest/v1/${table}?select=*`, {
        headers: { apikey: key, Authorization: `Bearer ${key}` },
    });
    if (!res.ok) {
        console.warn(`skip ${table}: ${res.status}`);
        continue;
    }
    const rows = await res.json();
    console.log(`${table}: ${rows.length} rows`);
    if (!rows.length) continue;
    const json = JSON.stringify(rows).replace(/'/g, "''");
    lines.push(`INSERT INTO ${table} SELECT * FROM json_populate_recordset(NULL::${table}, '${json}');`);
}

writeFileSync("supabase/seed.sql", lines.join("\n\n") + "\n");
console.log("Wrote supabase/seed.sql");
